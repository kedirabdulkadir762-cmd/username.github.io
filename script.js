function changeLanguage(lang){

if(lang=="or"){

document.getElementById("course").innerText="Koorsiiwwan"
document.getElementById("materials").innerText="Meeshaalee Barnootaa"

}

else if(lang=="am"){

document.getElementById("course").innerText="ኮርሶች"
document.getElementById("materials").innerText="የትምህርት እቃዎች"

}

else{

document.getElementById("course").innerText="Courses"
document.getElementById("materials").innerText="Learning Materials"

}

}
